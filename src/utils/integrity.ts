function rotr(n: number, x: number): number {
  return (x >>> n) | (x << (32 - n));
}

/**
 * Incremental SHA-256 calculator that processes arbitrary-sized chunks in O(1) RAM.
 * Supports 1 GB / 5 GB+ files streamed slice-by-slice.
 */
export class StreamingSha256 {
  private h = new Uint32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
    0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ]);
  private buffer = new Uint8Array(64);
  private bufferLength = 0;
  private bytesProcessed = 0;
  private w = new Uint32Array(64);

  update(chunk: Uint8Array): this {
    let offset = 0;
    const len = chunk.byteLength;
    this.bytesProcessed += len;

    if (this.bufferLength > 0) {
      const take = Math.min(64 - this.bufferLength, len);
      this.buffer.set(chunk.subarray(0, take), this.bufferLength);
      this.bufferLength += take;
      offset += take;
      if (this.bufferLength === 64) {
        this.processBlock(this.buffer, 0);
        this.bufferLength = 0;
      }
    }

    while (offset + 64 <= len) {
      this.processBlock(chunk, offset);
      offset += 64;
    }

    if (offset < len) {
      const remaining = len - offset;
      this.buffer.set(chunk.subarray(offset), 0);
      this.bufferLength = remaining;
    }

    return this;
  }

  private processBlock(block: Uint8Array, offset: number): void {
    const w = this.w;
    for (let i = 0; i < 16; i++) {
      const j = offset + i * 4;
      w[i] =
        ((block[j] << 24) |
          (block[j + 1] << 16) |
          (block[j + 2] << 8) |
          block[j + 3]) >>>
        0;
    }

    for (let i = 16; i < 64; i++) {
      const s0 = rotr(7, w[i - 15]) ^ rotr(18, w[i - 15]) ^ (w[i - 15] >>> 3);
      const s1 = rotr(17, w[i - 2]) ^ rotr(19, w[i - 2]) ^ (w[i - 2] >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) >>> 0;
    }

    let a = this.h[0];
    let b = this.h[1];
    let c = this.h[2];
    let d = this.h[3];
    let e = this.h[4];
    let f = this.h[5];
    let g = this.h[6];
    let h = this.h[7];

    for (let i = 0; i < 64; i++) {
      const S1 = rotr(6, e) ^ rotr(11, e) ^ rotr(25, e);
      const ch = (e & f) ^ (~e & g);
      const temp1 = (h + S1 + ch + SHA256_K[i] + w[i]) >>> 0;
      const S0 = rotr(2, a) ^ rotr(13, a) ^ rotr(22, a);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (S0 + maj) >>> 0;

      h = g;
      g = f;
      f = e;
      e = (d + temp1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (temp1 + temp2) >>> 0;
    }

    this.h[0] = (this.h[0] + a) >>> 0;
    this.h[1] = (this.h[1] + b) >>> 0;
    this.h[2] = (this.h[2] + c) >>> 0;
    this.h[3] = (this.h[3] + d) >>> 0;
    this.h[4] = (this.h[4] + e) >>> 0;
    this.h[5] = (this.h[5] + f) >>> 0;
    this.h[6] = (this.h[6] + g) >>> 0;
    this.h[7] = (this.h[7] + h) >>> 0;
  }

  digestHex(): string {
    const pad = new Uint8Array(128);
    pad.set(this.buffer.subarray(0, this.bufferLength), 0);
    pad[this.bufferLength] = 0x80;

    const totalBits = this.bytesProcessed * 8;
    const highBits = Math.floor(totalBits / 0x100000000);
    const lowBits = totalBits >>> 0;

    const padLen = this.bufferLength < 56 ? 64 : 128;
    const view = new DataView(pad.buffer);
    view.setUint32(padLen - 8, highBits, false);
    view.setUint32(padLen - 4, lowBits, false);

    this.processBlock(pad, 0);
    if (padLen === 128) {
      this.processBlock(pad, 64);
    }

    let hex = '';
    for (let i = 0; i < 8; i++) {
      hex += this.h[i].toString(16).padStart(8, '0');
    }
    return hex;
  }
}

export function computeSha256Bytes(data: Uint8Array): string {
  const hasher = new StreamingSha256();
  hasher.update(data);
  return hasher.digestHex();
}

export async function computeFileSha256Streaming(
  file: Blob,
  onProgress?: (bytesProcessed: number, totalBytes: number) => void
): Promise<string> {
  const CHUNK_SIZE = 4 * 1024 * 1024; // 4 MB bounded buffer
  const hasher = new StreamingSha256();
  let offset = 0;
  const total = file.size;

  while (offset < total) {
    const end = Math.min(offset + CHUNK_SIZE, total);
    const slice = file.slice(offset, end);
    const buf = await slice.arrayBuffer();
    hasher.update(new Uint8Array(buf));
    offset = end;
    if (onProgress) {
      onProgress(offset, total);
    }
  }

  return hasher.digestHex();
}

export function formatBytes(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes <= 0) return '0 B';
  const units = ['B', 'KB', 'MB', 'GB', 'TB'];
  const idx = Math.min(Math.floor(Math.log(bytes) / Math.log(1024)), units.length - 1);
  const val = bytes / Math.pow(1024, idx);
  return `${val >= 100 || idx === 0 ? val.toFixed(0) : val.toFixed(2)} ${units[idx]}`;
}

export function formatSpeed(bytesPerSec: number): string {
  if (!Number.isFinite(bytesPerSec) || bytesPerSec <= 0) return '0.0 KB/s';
  if (bytesPerSec >= 1024 * 1024) {
    return `${(bytesPerSec / (1024 * 1024)).toFixed(2)} MB/s`;
  }
  return `${(bytesPerSec / 1024).toFixed(1)} KB/s`;
}
